/**
 * In-memory map to store players' custom given names (e.g. from Name Tags)
 * to avoid overwriting them with mob type names.
 */
const customNameCache: Map<string, string> = new Map();

/**
 * In-memory cache of last rendered mob health state to avoid redundant string allocations,
 * pixel width calculations, and property updates on stationary/unhurt mobs.
 */
const mobHpCache = new Map<string, { hp: number; maxHp: number; name: string }>();

/** Dynamic property used to persist a player-given name across reloads. */
const CUSTOM_NAME_PROPERTY = "qol:custom_name";

/**
 * Returns true if a nameTag was generated by this feature (current or older builds),
 * so it is never mistaken for a player-given Name Tag.
 */
export function isGeneratedNameTag(tag: string): boolean {
    return (
        tag.includes("\n") ||
        tag.includes("§") ||
        /[\uE000-\uF8FF]/.test(tag) || // any custom font glyph
        /[▬■█❤♥|]{2,}/.test(tag) || // legacy text gauges
        /\d+\s*\/\s*\d+/.test(tag) // "20/20" style HP readouts
    );
}

/**
 * Resolves the player-given custom name for an entity (if any), caching it in memory
 * and persisting it as a dynamic property.
 */
export function resolveCustomName(entity: Entity): string | undefined {
    // A non-generated nameTag means a player just (re)named this mob
    const tag = entity.nameTag;
    if (tag && !isGeneratedNameTag(tag)) {
        if (customNameCache.get(entity.id) !== tag) {
            customNameCache.set(entity.id, tag);
            try {
                entity.setDynamicProperty(CUSTOM_NAME_PROPERTY, tag);
            } catch {
                // Dynamic properties unavailable — in-memory cache still works
            }
        }
        return tag;
    }

    const cached = customNameCache.get(entity.id);
    if (cached) return cached;

    try {
        const stored = entity.getDynamicProperty(CUSTOM_NAME_PROPERTY);
        if (typeof stored === "string" && stored.length > 0) {
            customNameCache.set(entity.id, stored);
            return stored;
        }
    } catch {
        // Ignore
    }
    return undefined;
}

/**
 * Checks if an entity has a genuine player-given custom Name Tag (from an anvil),
 * correctly distinguishing it from generated UI nameplates like health bars.
 */
export function isPlayerNamedEntity(entity: Entity): boolean {
    if (!entity || !entity.isValid) return false;
    const customName = resolveCustomName(entity);
    return Boolean(customName && customName.trim().length > 0);
}

/**
 * Formats an entity typeId into a readable title.
 * e.g. "minecraft:zombified_piglin" -> "Zombified Piglin"
 */
export function formatEntityTypeName(typeId: string): string {
    if (typeId === "minecraft:zombie_pigman" || typeId === "minecraft:zombified_piglin") {
        return "Zombified Piglin";
    }
    if (typeId === "minecraft:zombie_villager" || typeId === "minecraft:zombie_villager_v2") {
        return "Zombie Villager";
    }
    if (typeId === "minecraft:villager" || typeId === "minecraft:villager_v2") {
        return "Villager";
    }
    if (typeId === "minecraft:evocation_illager") {
        return "Evoker";
    }
    const raw = typeId.replace(/^minecraft:/, "");
    return raw
        .split("_")
        .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
        .join(" ");
}

/**
 * Checks whether an entity is eligible to display an HP bar.
 */
export function isEligibleMob(entity: Entity): boolean {
    if (!entity || !entity.isValid) return false;
    if (entity.typeId === "minecraft:player") return false;

    // Check hostile mobs
    if (HOSTILE_MOBS.has(entity.typeId)) {
        return MobHealthBarConfig.showHostileMobs;
    }

    // Check neutral mobs
    if (NEUTRAL_MOBS.has(entity.typeId)) {
        return MobHealthBarConfig.showNeutralMobs;
    }

    // Check passive mobs
    if (PASSIVE_MOBS.has(entity.typeId)) {
        return MobHealthBarConfig.showPassiveMobs;
    }

    return false;
}

/**
 * Formats the mob's name using standard Minecraft vanilla styling.
 * Uses regular-weight white (§f) for all mob names to match the modern template card design.
 */
export function getMobNameHeader(entity: Entity): { name: string; color: string } {
    // Check if mob has a custom name from a player nametag
    const custom = resolveCustomName(entity);
    if (custom) {
        return { name: custom, color: "§f" };
    }

    return { name: formatEntityTypeName(entity.typeId), color: "§f" };
}

/**
 * Custom pill-segment glyphs from resource_pack/font/glyph_E1.png
 * (generated by scripts/generate_health_glyphs.py — keep the layout in sync).
 *   Empty track: U+E100 + shape
 *   Filled:      U+E100 + 4 + (color * 4 + shape) * GAUGE_LEVELS + (level - 1)
 */
const GLYPH_BASE = 0xe100;
/** Fill steps (pixel columns) per segment glyph. */
const GAUGE_LEVELS = 15;
const enum GaugeColor {
    Green = 0,
    Amber = 1,
    Red = 2,
}
const enum GaugeShape {
    LeftCap = 0,
    Middle = 1,
    RightCap = 2,
    Single = 3,
}

/** Approximate on-screen width (font pixels) of one gauge segment glyph. */
const SEGMENT_PX = 9;

/** Returns the glyph for one segment filled `level` (0..GAUGE_LEVELS) pixel columns. */
function gaugeGlyph(color: GaugeColor, shape: GaugeShape, level: number): string {
    if (level <= 0) {
        return String.fromCharCode(GLYPH_BASE + shape);
    }
    const lvl = Math.min(GAUGE_LEVELS, level);
    return String.fromCharCode(GLYPH_BASE + 4 + (color * 4 + shape) * GAUGE_LEVELS + (lvl - 1));
}

function segmentShape(index: number, total: number): GaugeShape {
    if (total === 1) return GaugeShape.Single;
    if (index === 0) return GaugeShape.LeftCap;
    if (index === total - 1) return GaugeShape.RightCap;
    return GaugeShape.Middle;
}

/**
 * Builds the modern segmented health bar gauge matching the template design.
 * The fill is proportional to HP at 1-pixel precision (segments drain partially),
 * colored by remaining health:
 * - Green (ratio > 0.50)
 * - Amber (0.25 < ratio <= 0.50)
 * - Red (ratio <= 0.25)
 * Unfilled portions are rendered as a dark track.
 * Uses custom resource-pack glyphs (rounded pill segments with thin gaps).
 */
export function buildSegmentedGauge(currentHp: number, maxHp: number, totalSegments: number = 4): string {
    const safeMax = Math.max(1, maxHp);
    const ratio = Math.max(0, Math.min(1, currentHp / safeMax));
    const segmentsTotal = Math.max(1, Math.floor(totalSegments));

    // Total filled pixel columns across the whole bar
    let filledPx = Math.round(ratio * segmentsTotal * GAUGE_LEVELS);
    if (currentHp > 0 && filledPx === 0) {
        filledPx = 1; // Always show a sliver if the mob is still alive
    }
    if (currentHp < safeMax && filledPx >= segmentsTotal * GAUGE_LEVELS) {
        filledPx = segmentsTotal * GAUGE_LEVELS - 1; // Never look full when damaged
    }

    let fillColor = GaugeColor.Green;
    if (ratio <= 0.25) {
        fillColor = GaugeColor.Red;
    } else if (ratio <= 0.5) {
        fillColor = GaugeColor.Amber;
    }

    let gauge = "§r§f"; // White = glyph colors are rendered unmodified
    for (let i = 0; i < segmentsTotal; i++) {
        const level = Math.max(0, Math.min(GAUGE_LEVELS, filledPx - i * GAUGE_LEVELS));
        gauge += gaugeGlyph(fillColor, segmentShape(i, segmentsTotal), level);
    }
    return gauge;
}

/**
 * Backwards-compatibility alias for buildSegmentedGauge.
 */
export const buildXpGauge = buildSegmentedGauge;

/**
 * Approximate Bedrock default-font advance widths (font pixels, incl. spacing).
 */
function textPixelWidth(text: string): number {
    let width = 0;
    for (const ch of text) {
        if ("!.,:;|i'".includes(ch)) width += 2;
        else if ("l`".includes(ch)) width += 3;
        else if (" tI[]".includes(ch)) width += 4;
        else if ("fk<>(){}\"*".includes(ch)) width += 5;
        else if ("@~".includes(ch)) width += 7;
        else width += 6;
    }
    return width;
}

/**
 * Formats Line 1 of the mob health card:
 * Left: White mob name (§fMobName)
 * Right: Numeric HP fraction (e.g. §f20§7/20, or §c3§7/20 on low health)
 */
export function formatMobCardHeader(mobName: string, currentHp: number, maxHp: number): string {
    const safeMax = Math.max(1, maxHp);
    const ratio = Math.max(0, Math.min(1, currentHp / safeMax));

    const curVal = Math.ceil(currentHp);
    const maxVal = Math.round(maxHp);

    // Current HP turns red when critical (<= 25%), otherwise white
    const curColor = ratio <= 0.25 ? "§c" : "§f";
    const hpFraction = MobHealthBarConfig.showHpValue ? `${curColor}${curVal}§7/${maxVal}` : "";

    if (!MobHealthBarConfig.showMobName) {
        return hpFraction;
    }

    if (!MobHealthBarConfig.showHpValue) {
        return `§f${mobName}`;
    }

    // Pad so the name sits flush-left and HP flush-right above the gauge
    const barWidth = Math.max(1, MobHealthBarConfig.gaugeSegments) * SEGMENT_PX;
    const contentWidth = textPixelWidth(mobName) + textPixelWidth(`${curVal}/${maxVal}`);
    const spaceCount = Math.max(2, Math.round((barWidth - contentWidth) / 4));
    const padding = " ".repeat(spaceCount);

    return `§f${mobName}${padding}${hpFraction}`;
}

/**
 * Backwards-compatibility helper for HP formatting.
 */
export function formatHpValue(currentHp: number, maxHp: number): string {
    const safeMax = Math.max(1, maxHp);
    const ratio = Math.max(0, Math.min(1, currentHp / safeMax));
    const curVal = Math.ceil(currentHp);
    const maxVal = Math.round(maxHp);
    const curColor = ratio <= 0.25 ? "§c" : "§f";
    return `${curColor}${curVal}§7/${maxVal}`;
}

/**
 * Set of block identifier substrings that do not block line-of-sight visibility.
 */
const SEE_THROUGH_BLOCKS = [
    "glass",
    "leaves",
    "bars",
    "fence",
    "gate",
    "scaffolding",
    "ladder",
    "banner",
    "slime",
    "honey_block",
    "grindstone",
    "lantern",
    "chain",
];

/**
 * Checks if a block is solid and occludes visual line of sight.
 */
export function isOccludingBlock(block: Block | undefined): boolean {
    if (!block || !block.isValid) return false;
    if (block.isAir || block.isLiquid) return false;

    const id = block.typeId;
    for (const sub of SEE_THROUGH_BLOCKS) {
        if (id.includes(sub)) return false;
    }
    return true;
}

/**
 * Checks if a player has direct visual line of sight to an entity.
 */
export function hasLineOfSight(player: Player, entity: Entity): boolean {
    try {
        if (!player || !player.isValid || !entity || !entity.isValid) return false;
        if (player.dimension.id !== entity.dimension.id) return false;

        const eyePos = player.getHeadLocation();
        const entLoc = entity.location;

        const targetPos = {
            x: entLoc.x,
            y: entLoc.y + 1.0,
            z: entLoc.z,
        };

        const dx = targetPos.x - eyePos.x;
        const dy = targetPos.y - eyePos.y;
        const dz = targetPos.z - eyePos.z;
        const dist = Math.hypot(dx, dy, dz);

        // Immediate proximity is always considered visible
        if (dist <= 1.5) return true;

        const dir = {
            x: dx / dist,
            y: dy / dist,
            z: dz / dist,
        };

        let currentStart = eyePos;
        let remainingDist = Math.max(0.2, dist - 0.4);

        while (remainingDist > 0.5) {
            const hit = player.dimension.getBlockFromRay(currentStart, dir, {
                maxDistance: remainingDist,
                includeLiquidBlocks: false,
                includePassableBlocks: false,
            });

            if (!hit) {
                return true; // No solid obstruction along the path
            }

            if (!isOccludingBlock(hit.block)) {
                // Transparent / see-through block (e.g. glass window, leaves, iron bars)
                currentStart = {
                    x: hit.faceLocation.x + dir.x * 0.15,
                    y: hit.faceLocation.y + dir.y * 0.15,
                    z: hit.faceLocation.z + dir.z * 0.15,
                };
                const traveled = Math.hypot(
                    currentStart.x - eyePos.x,
                    currentStart.y - eyePos.y,
                    currentStart.z - eyePos.z
                );
                remainingDist = (dist - 0.4) - traveled;
            } else {
                // Hit a solid opaque block (stone, wood, cobblestone, etc.)
                return false;
            }
        }

        return true;
    } catch {
        return true; // Fallback to visible if raycast fails
    }
}

/**
 * Updates an entity's floating nameTag with the modern segmented card design.
 */
export function updateEntityHealthBar(entity: Entity): void {
    if (!MobHealthBarConfig.enabled || !isEligibleMob(entity)) {
        return;
    }

    try {
        const healthComp = entity.getComponent(EntityComponentTypes.Health) as EntityHealthComponent | undefined;
        if (!healthComp) return;

        const currentHp = Math.max(0, healthComp.currentValue);
        const maxHp = healthComp.effectiveMax;

        if (currentHp <= 0) {
            // Clear floating text immediately upon death
            entity.nameTag = "";
            customNameCache.delete(entity.id);
            mobHpCache.delete(entity.id);
            return;
        }

        // Resolves player Name Tags (ignores any previously generated health-bar text)
        const { name } = getMobNameHeader(entity);

        // Check if health and name have not changed since last render
        const cached = mobHpCache.get(entity.id);
        if (cached && cached.hp === currentHp && cached.maxHp === maxHp && cached.name === name) {
            return; // State unchanged, skip update
        }
        mobHpCache.set(entity.id, { hp: currentHp, maxHp, name });

        const line1 = formatMobCardHeader(name, currentHp, maxHp);
        const line2 = buildSegmentedGauge(currentHp, maxHp, MobHealthBarConfig.gaugeSegments);

        const newTag = `${line1}\n${line2}`;
        if (entity.nameTag !== newTag) {
            entity.nameTag = newTag;
        }

        // Configure nameplate render distance on platforms supporting it
        try {
            (entity as any).nameplateRenderDistance = MobHealthBarConfig.nameplateRenderDistance ?? MobHealthBarConfig.maxDisplayDistance ?? 64;
        } catch {
            // Fallback for earlier engine versions
        }

        // Configure nameplate depth testing based on phaseThroughWalls
        try {
            const depthTested = !MobHealthBarConfig.phaseThroughWalls;
            (entity as any).nameplateDepthTested = depthTested;
        } catch {
            // Graceful fallback for older platforms
        }
    } catch {
        // Silently skip if entity unloaded
    }
}

/**
 * Clears the health bar nameTag from an entity.
 */
export function clearEntityHealthBar(entity: Entity): void {
    if (!entity || !entity.isValid) return;
    try {
        const cached = customNameCache.get(entity.id);
        entity.nameTag = cached ?? "";
        mobHpCache.delete(entity.id);
    } catch {
        // Ignore
    }
}

/**
 * Initializes the Mob Health Bar feature with event listeners and periodic scanner.
 */
export function initMobHealthBarFeature(): void {
    if (!MobHealthBarConfig.enabled) {
        console.warn("[MobHealthBar] Feature is disabled in configuration.");
        return;
    }

    // 1. Instant update on entity spawn (0-tick real-time responsiveness)
    world.afterEvents.entitySpawn.subscribe((event) => {
        const spawned = event.entity;
        if (spawned && spawned.isValid && isEligibleMob(spawned)) {
            const phaseThroughWalls = MobHealthBarConfig.phaseThroughWalls ?? false;
            if (phaseThroughWalls) {
                updateEntityHealthBar(spawned);
            } else {
                const players = Array.from(world.getAllPlayers());
                const isVisible = players.some(
                    (p) =>
                        p.dimension.id === spawned.dimension.id &&
                        Math.hypot(p.location.x - spawned.location.x, p.location.z - spawned.location.z) <= MobHealthBarConfig.maxDisplayDistance &&
                        hasLineOfSight(p, spawned)
                );
                if (isVisible) {
                    updateEntityHealthBar(spawned);
                }
            }
        }
    });

    // 2. Instant update on damage event (0-tick real-time responsiveness)
    world.afterEvents.entityHurt.subscribe((event) => {
        const hurt = event.hurtEntity;
        if (hurt && hurt.isValid && isEligibleMob(hurt)) {
            const phaseThroughWalls = MobHealthBarConfig.phaseThroughWalls ?? false;
            if (phaseThroughWalls) {
                updateEntityHealthBar(hurt);
            } else {
                const players = Array.from(world.getAllPlayers());
                const isVisible = players.some(
                    (p) =>
                        p.dimension.id === hurt.dimension.id &&
                        Math.hypot(p.location.x - hurt.location.x, p.location.z - hurt.location.z) <= MobHealthBarConfig.maxDisplayDistance &&
                        hasLineOfSight(p, hurt)
                );
                if (isVisible) {
                    updateEntityHealthBar(hurt);
                }
            }
        }
    });

    // 3. Clear nameTag on entity death
    world.afterEvents.entityDie.subscribe((event) => {
        const dead = event.deadEntity;
        if (dead && dead.isValid) {
            dead.nameTag = "";
            customNameCache.delete(dead.id);
            mobHpCache.delete(dead.id);
        }
    });

    // 4. Periodic scan around online players (scans configurable sphere with line-of-sight check)
    system.runInterval(() => {
        const players = Array.from(world.getAllPlayers());
        if (players.length === 0) return;

        const maxDist = MobHealthBarConfig.maxDisplayDistance;
        const processed = new Set<string>();
        const phaseThroughWalls = MobHealthBarConfig.phaseThroughWalls ?? false;

        for (const player of players) {
            if (!player || !player.isValid) continue;

            try {
                const nearbyEntities = player.dimension.getEntities({
                    location: player.location,
                    maxDistance: maxDist,
                });

                for (const entity of nearbyEntities) {
                    if (processed.has(entity.id)) continue;
                    if (!isEligibleMob(entity)) continue;

                    processed.add(entity.id);

                    if (phaseThroughWalls) {
                        // Mode 1: Phase through walls (X-ray / radar style)
                        updateEntityHealthBar(entity);
                    } else {
                        // Mode 2: Only render if at least one online player has direct visual line of sight
                        let isVisible = hasLineOfSight(player, entity);
                        if (!isVisible && players.length > 1) {
                            for (const otherPlayer of players) {
                                if (otherPlayer.id === player.id) continue;
                                if (otherPlayer.dimension.id !== entity.dimension.id) continue;
                                const dist = Math.hypot(
                                    otherPlayer.location.x - entity.location.x,
                                    otherPlayer.location.z - entity.location.z
                                );
                                if (dist <= maxDist && hasLineOfSight(otherPlayer, entity)) {
                                    isVisible = true;
                                    break;
                                }
                            }
                        }

                        if (isVisible) {
                            updateEntityHealthBar(entity);
                        } else {
                            clearEntityHealthBar(entity);
                        }
                    }
                }
            } catch {
                // Ignore dimension transition errors
            }
        }
    }, MobHealthBarConfig.updateIntervalTicks);

    console.warn("[MobHealthBar] Feature initialized successfully.");
}

